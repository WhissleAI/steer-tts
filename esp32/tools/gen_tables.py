#!/usr/bin/env python3
"""Generate components/steertts_nano/src/nano_tables.c (constant tables that live in flash).

nano_cs2048[2k], [2k+1] = cos, sin(2 pi k / 2048), k < 1024: real-FFT twiddles and the Hann window for any
n_fft <= 2048 (stride 2048 / n_fft).
nano_fftw1024: radix-2 complex FFT twiddles for any complex size <= 1024, in the layout of esp-dsp's
dsps_fft2r_fc32 (cos, sin(2 pi i / 1024) for i < 512, in bit-reversed order over 512 entries)."""
import math
import os

import numpy as np


def bitrev(i, bits):
    return int(format(i, f"0{bits}b")[::-1], 2)


def main():
    cs = np.zeros(2048, np.float32)
    for k in range(1024):
        cs[2 * k] = math.cos(2 * math.pi * k / 2048)
        cs[2 * k + 1] = math.sin(2 * math.pi * k / 2048)
    w = np.zeros(1024, np.float32)
    for j in range(512):
        i = bitrev(j, 9)
        w[2 * j] = math.cos(2 * math.pi * i / 1024)
        w[2 * j + 1] = math.sin(2 * math.pi * i / 1024)

    def arr(name, a):
        vals = ", ".join((lambda t: t if ("." in t or "e" in t) else t + ".0")(f"{float(v):.9g}") + "f" for v in a)
        lines = []
        cur = ""
        for tok in vals.split(", "):
            if len(cur) + len(tok) + 2 > 116:
                lines.append(cur.rstrip())
                cur = ""
            cur += tok + ", "
        lines.append(cur.rstrip().rstrip(","))
        return f"const float {name}[{len(a)}] __attribute__((aligned(16))) = {{\n    " + "\n    ".join(lines) + "\n};\n"

    out = os.path.join(os.path.dirname(__file__), "..", "components", "steertts_nano", "src", "nano_tables.c")
    with open(out, "w") as f:
        f.write("/* Generated by tools/gen_tables.py, do not edit. */\n#include \"nano_tables.h\"\n\n")
        f.write(arr("nano_cs2048", cs) + "\n" + arr("nano_fftw1024", w))
    print(out)


if __name__ == "__main__":
    main()
